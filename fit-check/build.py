#!/usr/bin/env python3
"""Build fit-check/index.html from src/template.html.

Injects:
  - config.json                      -> CONFIG (study name, contact, backend URL)
  - src/instrument.json              -> INSTRUMENT (items, keys, scales; single source of truth)
  - the shared engine blocks marked  /* @@SHARED:<name>:start */ ... /* @@SHARED:<name>:end */
    in ../culture-fit-architect/index.html (model, parsers, guide), so the participant app and
    the assessor tool always score fit with identical code.
Also regenerates docs/item-bank.md from the instrument.

Usage:  python3 build.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent
ENGINE = ROOT.parent / "culture-fit-architect" / "index.html"


def shared_block(src: str, name: str) -> str:
    m = re.search(r"/\* @@SHARED:%s:start[^*]*\*/\n(.*?)\n/\* @@SHARED:%s:end \*/" % (name, name), src, re.S)
    if not m:
        raise SystemExit(f"Shared block '{name}' not found in {ENGINE}")
    return m.group(1)


def item_bank(inst: dict) -> str:
    out = [f"# {inst['name']} item bank ({inst['version']})", "",
           "Generated by `build.py` from `src/instrument.json`. Do not edit by hand.", "",
           "Keys: `+` scored as answered, `−` reverse-scored (6 − answer). Scale scores are item means rescaled to 0–100.", ""]
    for block, meta in inst["blocks"].items():
        items = [i for i in inst["items"] if i["block"] == block]
        out += [f"## {meta['title']} ({len(items)} items)", "", f"_Instruction:_ {meta['intro']}", "",
                f"_Response scale:_ {' · '.join(inst['response_scales'][items[0]['rs']])}", "",
                "| ID | Scale | Key | Item |", "|---|---|---|---|"]
        for i in items:
            scale = "attention check" if i["scale"] == "CHECK" else f"{inst['scales'][i['scale']]['label']} (`{i['scale']}`)"
            key = {1: "+", -1: "−", 0: f"correct = {inst['checks'].get(i['id'])}"}[i["key"]]
            out.append(f"| {i['id']} | {scale} | {key} | {i['text']} |")
        out.append("")
    out += ["## Scale sources", "", "| Scale | Label | Items | Source / status |", "|---|---|---|---|"]
    for sc, meta in inst["scales"].items():
        n = sum(1 for i in inst["items"] if i["scale"] == sc)
        out.append(f"| `{sc}` | {meta['label']} | {n} | {meta['source']} |")
    return "\n".join(out) + "\n"


def main() -> None:
    engine = ENGINE.read_text(encoding="utf-8")
    template = (ROOT / "src" / "template.html").read_text(encoding="utf-8")
    inst = json.loads((ROOT / "src" / "instrument.json").read_text(encoding="utf-8"))
    config = json.loads((ROOT / "config.json").read_text(encoding="utf-8"))
    as_js = lambda o: json.dumps(o, ensure_ascii=False).replace("</", "<\\/")
    html = template
    html = re.sub(r"/\*@@CONFIG\*/.*?/\*@@END\*/", lambda _: as_js(config), html, count=1, flags=re.S)
    html = re.sub(r"/\*@@INSTRUMENT\*/.*?/\*@@END\*/", lambda _: as_js(inst), html, count=1, flags=re.S)
    for name in ("model", "parsers", "guide"):
        html = html.replace(f"/*@@INJECT:{name}*/", f"/* shared engine: {name} (from culture-fit-architect) */\n" + shared_block(engine, name), 1)
    if "@@" in html:
        raise SystemExit("Unresolved placeholder left in template")
    (ROOT / "index.html").write_text(html, encoding="utf-8")
    (ROOT / "docs" / "item-bank.md").write_text(item_bank(inst), encoding="utf-8")
    print(f"Built index.html ({len(html) // 1024} KB), {len(inst['items'])} items; docs/item-bank.md updated")


if __name__ == "__main__":
    main()
